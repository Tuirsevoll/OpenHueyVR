\ item-test-room - every item in the game laid out in rows, to test each one's model, how it
\ sits in the hand and its grip (HGVR, branch item-model-overhaul). Generated by gen.py.
\
\ How it works: the game's own VR loot props (loot-at, src/game/loot.c) - the same ones a room's
\ sparkles become - put down at spots in rows in front of Fiona. Each gets a pickup word of this
\ mod's (loot-script), so letting go of one never runs the game's pickup: nothing goes into the
\ inventory, no story fact is set, and the item goes straight back to its spot (story/kit.fs
\ loot-finish: a prop with no fact is kept). `item-test-real` switches that: each one let go is
\ then given for real (into the inventory) and leaves the table until the page is laid out again.
\
\ The game holds 32 loot props at once (loot.c LOOT_N), so the 104 items come in 5 pages.
\   Title screen: ITEM TEST ROOM - a fresh game, straight into the test room.
\   Console (` key):  item-test        to the test room, page 1 laid out in front of her
\                     item-test-here   the current page laid out in front of her, wherever she is
\                     item-test-next / item-test-back / n item-test-page    another page
\                     item-test-reset  the page put back on its spots   item-test-clear  all gone
\                     item-test-real / item-test-safe   given for real, or not (the default)
\                     item-test-floor / item-test-table  on the floor, or at table height (default)
\                     item-test-flip   rows mirrored     item-test-up   'up' turned over (items under the floor)
\                     item-test-list   every page and row printed
\   Keys while it is on: F6 next page, F7 page back, F8 lay the page out again where she stands now.
\ Don't press F5 (quick save) while testing.
\
\ Directions (the game's y axis points DOWN - see the README): her facing is (sin yaw, cos yaw) in
\ x z, the game's own convention (story/kit.fs turn-to: yaw = atan2(dx, dz)); rows go out along it
\ and across along (cos yaw, -sin yaw). Which way is up is not assumed: it is measured as the page
\ is laid out (her head's y against her feet' y), so it is right either way.
