\ which way is up: her head's y (fiona/looks.fs tell-head: her head bone) against her feet' (it-oy, set first)
: it-find-up ( -- )
    fiona-id body-head vectors:v.y sf@  it-oy f@ f-  0e f< if  -1  else  1  then
    it-up-turn @ *  it-up ! ;
: it-set-origin ( -- )   \ from where she stands now, the way she faces
    fiona-id body-pos  it-oz f!  it-oy f!  it-ox f!
    fiona-id body-yaw  it-oyaw f!
    it-find-up  -1 it-placed ! ;

\ a spot d out along her facing and a across along (cos yaw, -sin yaw), up by the table height
: it-at ( -- ) ( F: a d -- x y z )
    {: F: a d | F: fx fz :}
    it-oyaw f@ fsin  to fx   it-oyaw f@ fcos  to fz
    it-ox f@  fx d f* f+  fz a f* f+
    it-oy f@  it-on-table @ if  it-table it-up @ s>f f* f+  then
    it-oz f@  fz d f* f+  fx a f* f- ;
: it-spot ( e -- ) ( F: -- x y z )   \ an entry's spot: its row out, its column across (the row centred)
    {: e :}
    e e-col s>f  e e-cols 1- s>f 0.5e f*  f-  it-spacing f*  it-flip @ s>f f*
    e e-row s>f  it-row-gap f*  it-first-row f+
    it-at ;
